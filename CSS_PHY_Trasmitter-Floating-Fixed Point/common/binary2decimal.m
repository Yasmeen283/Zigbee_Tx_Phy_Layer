function [decimal] = binary2decimal(binary,bitsnumber,decimal_length)
% ----------------------------------------------------------------------- %
% ======================================================================= %
% decimal2binary : Function Summary
% ----------------------------------------------------------------------- %
%  Binary to Decimal convertion
% ======================================================================= %
% ----------------------------------------------------------------------- %
% generate the base power 2 matrix 
 power(bitsnumber:-1:1) = 2 .^ ((1 : bitsnumber)-1);
 power_matrix  = repmat (power,decimal_length,1);
 % ---------------------------------------------------------------------- %
 % convert form binary to decimal.
 % Example input (101,3,1)
 % power_matrix = [ 4 2 1 ]
 % output = sum [1 0 1] .* [4 2 1] = 4+ 0+1 = 5;
 decimal = sum (power_matrix .*  binary,2) ;
% ----------------------------------------------------------------------- %
end
